# Re-time a finished picture to a new voice take without touching its frame numbers: match the words of the old and
# new takes (same script), and write a piecewise-linear map between old and new frames.
# Usage: python scripts/make_warp.py <old words.json> <new words.json> <new voice.wav> <out warp.ts> <out warp.json> <SCRIPT.md> <story.ts>
import difflib
import json
import re
import sys
import wave

FPS = 30
old = json.load(open(sys.argv[1], encoding="utf-8"))
new = json.load(open(sys.argv[2], encoding="utf-8"))
with wave.open(sys.argv[3]) as w:
    new_dur = w.getnframes() / w.getframerate()
OLD_TOTAL = 2064  # frames of the picture as built (story.ts TOTAL)
NEW_TOTAL = int(round(new_dur * FPS))

norm = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())
# split merged tokens ("In 1983") so both lists hold one written word per entry
def flat(ws):
    out = []
    for w in ws:
        parts = w["w"].split()
        for k, p in enumerate(parts):
            s = w["s"] + (w["e"] - w["s"]) * k / len(parts)
            out.append((norm(p), s, w["e"] if k == len(parts) - 1 else s + (w["e"] - w["s"]) / len(parts)))
    return out
A, B = flat(old), flat(new)
sm = difflib.SequenceMatcher(a=[x[0] for x in A], b=[x[0] for x in B], autojunk=False)
# anchors: the first word of every script line + every cue word the picture times an action to (story.ts W);
# anchoring every word follows the jitter of word timings and makes motion stutter
match = {}
for blk in sm.get_matching_blocks():
    for k in range(blk.size):
        match[blk.a + k] = blk.b + k
script = sys.argv[6] if len(sys.argv) > 6 else None
keep = set()
if script:
    i = 0
    for ln in open(script, encoding="utf-8"):
        m = re.match(r"^\d+\. (.*)$", ln.strip())
        if m:
            keep.add(i); i += len(re.sub(r"\s*\*\([^)]*\)\*", "", m.group(1)).replace(" — ", " ").split())
cues = [int(x) for x in re.findall(r"[a-zA-Z0-9]+: (\d+)", re.search(r"export const W = \{(.*?)\};", open(sys.argv[7], encoding="utf-8").read(), re.S).group(1))] if len(sys.argv) > 7 else []
for fw in cues:
    keep.add(min(range(len(A)), key=lambda j: abs(A[j][1] * FPS - fw)))
pairs = [(0.0, 0.0)] + [(A[j][1] * FPS, B[match[j]][1] * FPS) for j in sorted(keep) if j in match]
print(f"line+cue anchors kept: {len(keep)} ({len(cues)} cues)")
pairs.append((OLD_TOTAL, NEW_TOTAL))
# keep it strictly increasing on both axes, at least 2 frames apart
po, pn = [], []
for o, n in sorted(pairs):
    if po and (o - po[-1] < 2 or n - pn[-1] < 2):
        continue
    po.append(round(o, 2)); pn.append(round(n, 2))
matched = sum(b.size for b in sm.get_matching_blocks())
json.dump({"old": po, "new": pn, "old_total": OLD_TOTAL, "new_total": NEW_TOTAL}, open(sys.argv[5], "w"))
open(sys.argv[4], "w", encoding="utf-8").write(
    "// GENERATED by scripts/make_warp.py: maps frames of the new voice take to the frames the picture was built on\n"
    "// (old scratch voice), anchored on every matched word. Edit the picture in old frames; this keeps it in sync.\n"
    f"export const NEW_TOTAL = {NEW_TOTAL};\n"
    f"const NEW = {json.dumps(pn)};\n"
    f"const OLD = {json.dumps(po)};\n"
    "const interp = (x: number, xs: number[], ys: number[]) => {\n"
    "  if (x <= xs[0]) return ys[0];\n"
    "  for (let i = 1; i < xs.length; i++) if (x <= xs[i]) return ys[i - 1] + ((ys[i] - ys[i - 1]) * (x - xs[i - 1])) / (xs[i] - xs[i - 1]);\n"
    "  return ys[ys.length - 1];\n"
    "};\n"
    "/** new-take frame -> picture frame (fractional) */\n"
    "export const toOld = (f: number) => interp(f, NEW, OLD);\n"
    "/** picture frame -> new-take frame */\n"
    "export const toNew = (f: number) => interp(f, OLD, NEW);\n")
rates = [(pn[i + 1] - pn[i]) / (po[i + 1] - po[i]) for i in range(len(po) - 1)]
print(f"{matched}/{len(A)} old words matched to {len(B)} new; {len(po)} anchors; {OLD_TOTAL} -> {NEW_TOTAL} frames; "
      f"local speed x{min(rates):.2f}..x{max(rates):.2f}")
